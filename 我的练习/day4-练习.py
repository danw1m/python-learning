# 4-1 华氏温度转摄氏温度
# 公式：C = (F - 32) / 1.8
# 输入华氏温度，输出保留一位小数
# 格式提示：print(f'{变量:.1f}') 会保留一位小数，f 加在引号前面，不是答案，是语法
b = float(input("请输入华氏度"))
c = (b - 32) / 1.8
print(f'{c:.1f}')
# 4-2 输入圆的半径，算周长和面积，都保留两位小数
# 公式：周长 2×π×r，面积 π×r²
# 圆周率用 math.pi，用之前要先 import math
n = float(input("请输入半径"))
import math
next_zc = 2 * math.pi * n
next_mj = math.pi * n **2
print(f'周长：{next_zc:.2f}')
print(f'面积：{next_mj:.2f}')


