# ============ 第1题　计数器 ============
# 统计 1 到 100 里有多少个偶数，只打印个数
# 骨架：
#   count = 0
#   for ...:
#       if 是偶数:
#           count ...
#   print(count)
count = 0
for i in range(1 , 101):
    if i % 2 == 0:
        count += 1
print(count)


# ============ 第2题　累加后要打印 ============
# 求 1 到 100 里能被 7 整除的数的和，最后只打印总和
# 注意：昨天你只打印了每个数，忘了打印总和
# 骨架：
#   total = 0
#   for ...:
#       if 能整除:
#           total ...
#   print(?)      ← 这一行别忘了
total = 0
for i in range(1 , 101):
    if i % 7 == 0:
        total += i
print(total)

